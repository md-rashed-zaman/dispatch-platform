#!/usr/bin/env bash
# Steady, realistic traffic for chaos experiments and dashboards (step 2.8): every couple of seconds the bank
# creates and publishes a job, Rahim accepts it once offered, the dispatcher lists work orders and opens a
# technician profile. Every request is logged as: time, endpoint, HTTP status, seconds.
#
#   scripts/traffic.sh > traffic.tsv          # runs until Ctrl-C (or DURATION seconds: DURATION=600)
#
# Needs the stack, the app (or API=http://localhost:8088 for the cluster) and the seed.
set -uo pipefail

API=${API:-http://localhost:8080}
KEYCLOAK=http://localhost:8180/realms/dispatch/protocol/openid-connect/token
DURATION=${DURATION:-0}
RAHIM_ID=01930000-0000-7000-8000-0000000000a1

login() {
  curl -sf "$KEYCLOAK" -d grant_type=password -d client_id=dispatch-dev-cli -d username="$1" -d password=password \
    | jq -r .access_token
}

# call NAME METHOD PATH TOKEN [JSON]: logs one line, prints the response body
call() {
  local name=$1 method=$2 path=$3 token=$4 body=${5:-}
  local args=(-s -o /tmp/traffic.$$ -w '%{http_code} %{time_total}' -X "$method" "$API$path" -H "Authorization: Bearer $token")
  [[ -n "$body" ]] && args+=(-H 'Content-Type: application/json' -d "$body")
  local result
  : > /tmp/traffic.$$ # a timed-out call must not hand the caller the previous response
  result=$(curl --max-time 30 "${args[@]}") || result="000 30" # no answer at all (refused, timed out)
  printf '%s\t%s\t%s\t%s\n' "$(date +%T)" "$name" "${result% *}" "${result#* }" >&3 # the log
  cat /tmp/traffic.$$ 2>/dev/null # the body, for the caller
}

exec 3>&1 # log lines go to the script's stdout even from inside $( )
started=$(date +%s)
tokens_at=0
while [[ "$DURATION" == 0 || $(( $(date +%s) - started )) -lt "$DURATION" ]]; do
  if (( $(date +%s) - tokens_at > 240 )); then # access tokens live 5 minutes
    DISPATCHER=$(login dispatcher.meghna); RAHIM=$(login tech.rahim); tokens_at=$(date +%s)
  fi

  id=$(call create POST /api/work-orders "$DISPATCHER" '{
    "title": "Traffic: CCTV check", "description": "Vault camera offline; the recorder lost its network link (generated by scripts/traffic.sh).",
    "siteAddress": "Gulshan Avenue, Dhaka", "site": {"latitude": 23.7930, "longitude": 90.4130},
    "requiredSkills": ["cctv", "networking"],
    "timeWindow": {"startsAt": "2026-12-01T04:00:00Z", "endsAt": "2026-12-01T08:00:00Z"},
    "budget": {"minor": 300000, "currency": "BDT"}, "checklist": ["Photo"]}' | jq -r '.id // empty' 2>/dev/null)
  if [[ -n "$id" ]]; then
    call publish POST "/api/work-orders/$id/publish" "$DISPATCHER" > /dev/null
    offer=""
    for _ in $(seq 20); do # matching offers it a moment after the publish
      offer=$(curl -s --max-time 5 "$API/api/me/offers?limit=50" -H "Authorization: Bearer $RAHIM" \
        | jq -r --arg wo "$id" '.items[]? | select(.workOrderId == $wo) | .id' 2>/dev/null)
      [[ -n "$offer" ]] && break
      sleep 0.25
    done
    [[ -n "$offer" ]] && call accept POST "/api/offers/$offer/accept" "$RAHIM" > /dev/null
  fi
  call list GET "/api/work-orders?limit=20" "$DISPATCHER" > /dev/null
  call profile GET "/api/technicians/$RAHIM_ID" "$DISPATCHER" > /dev/null
  sleep 2 # about 80 company requests a minute: under the rate limit (100), so 429s mean something
done
rm -f /tmp/traffic.$$
